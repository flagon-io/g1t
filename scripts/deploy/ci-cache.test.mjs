import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { depsHash, externalPackages, imageDigest, rustVersion, stale, unitHash, usedHashes } from "./ci-cache.mjs";
import { BUILDER } from "../cli-release.mjs";

const LOCK = (runner, serde) => `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "g1t-runner"
version = "${runner}"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "${serde}"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"
`;

test("a release's version bump keeps the Rust caches' key, a new dependency changes it", () => {
  assert.deepEqual(externalPackages(LOCK("0.3.3", "1.0.200")).length, 1);
  assert.equal(depsHash(LOCK("0.3.3", "1.0.200")), depsHash(LOCK("0.3.4", "1.0.200")));
  assert.notEqual(depsHash(LOCK("0.3.3", "1.0.200")), depsHash(LOCK("0.3.3", "1.0.201")));
  assert.match(depsHash(LOCK("0.3.3", "1.0.200")), /^[0-9a-f]{16}$/);
});

test("the toolchain is read from rustc -V", () => {
  assert.equal(rustVersion("rustc 1.99.0 (90b35a623 2026-09-30)\n"), "1.99.0");
  assert.equal(rustVersion("rustc 1.100.0-nightly (abc 2026-10-01)"), "1.100.0-nightly");
  assert.equal(rustVersion(""), null);
});

test("the CLI's builder image is pinned, and keys its cache by its digest", () => {
  assert.match(imageDigest(BUILDER), /^[0-9a-f]{12}$/);
  assert.equal(imageDigest(`ghcr.io/rust-cross/cargo-zigbuild@sha256:${"ab".repeat(32)}`), "abababababab");
  assert.equal(imageDigest("ghcr.io/rust-cross/cargo-zigbuild:latest"), null);
});

test("a unit's hash is read from its files and folders", () => {
  assert.equal(unitHash("libserde-0123456789abcdef.rlib"), "0123456789abcdef");
  assert.equal(unitHash("serde-0123456789abcdef"), "0123456789abcdef");
  assert.equal(unitHash("g1t_actions-0123456789abcdef.d"), "0123456789abcdef");
  assert.equal(unitHash("repository_workflows-0123456789abcdef"), "0123456789abcdef");
  assert.equal(unitHash("g1t"), null);
  assert.equal(unitHash("libg1t.rlib"), null);
});

test("only the units the build did not use are pruned", () => {
  const dir = mkdtempSync(join(tmpdir(), "ci-cache-"));
  try {
    const [used, old, script, run] = ["1111111111111111", "2222222222222222", "3333333333333333", "4444444444444444"];
    for (const sub of ["deps", "build", ".fingerprint"]) mkdirSync(join(dir, sub), { recursive: true });
    for (const f of [`libserde-${used}.rlib`, `libserde-${used}.rmeta`, `serde-${used}.d`, `libserde-${old}.rlib`, `serde-${old}.d`, `tests-${used}`]) {
      writeFileSync(join(dir, "deps", f), "x");
    }
    for (const d of [`serde-${script}`, `serde-${run}`, `serde-${old}`]) mkdirSync(join(dir, "build", d));
    for (const d of [`serde-${used}`, `serde-${script}`, `serde-${run}`, `serde-${old}`]) mkdirSync(join(dir, ".fingerprint", d));
    const messages = [
      "   Compiling serde",
      JSON.stringify({ reason: "compiler-artifact", filenames: [join(dir, "build", `serde-${script}`, "build-script-build")], executable: null }),
      JSON.stringify({ reason: "build-script-executed", out_dir: join(dir, "build", `serde-${run}`, "out") }),
      JSON.stringify({ reason: "compiler-artifact", filenames: [join(dir, "deps", `libserde-${used}.rlib`), join(dir, "deps", `libserde-${used}.rmeta`)] }),
      JSON.stringify({ reason: "compiler-artifact", filenames: [], executable: join(dir, "deps", `tests-${used}`) }),
      JSON.stringify({ reason: "build-finished", success: true }),
    ].join("\n");
    const hashes = usedHashes(messages);
    assert.deepEqual([...hashes].sort(), [used, script, run].sort());
    const gone = stale(dir, hashes)
      .map((p) => p.slice(dir.length + 1).replaceAll("\\", "/"))
      .sort();
    assert.deepEqual(gone, [`.fingerprint/serde-${old}`, `build/serde-${old}`, `deps/libserde-${old}.rlib`, `deps/serde-${old}.d`]);
    // Nothing listed: nothing would be kept, so the caller prunes nothing.
    assert.equal(usedHashes("error: could not compile").size, 0);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
