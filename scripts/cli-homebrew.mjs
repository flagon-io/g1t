// Generate a tap formula from a verified release manifest. Does not publish.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export function homebrewFormula(manifest) {
  assert.match(manifest.version, /^\d+\.\d+\.\d+$/, "A stable release is required");
  const blocks = ["macos", "linux"].map((os) => {
    const architectures = [["arm", "arm64"], ["intel", "x64"]].map(([arch, platform]) => {
      const name = `g1t-${os}-${platform}`;
      const file = manifest.files[`${os}-${platform}`];
      assert.equal(file?.name, name, `Missing or invalid ${name}`);
      assert.match(file.sha256, /^[a-f0-9]{64}$/, `Invalid checksum for ${name}`);
      return `    on_${arch} do\n      url "https://g1t.sh/downloads/cli/${manifest.version}/${name}", using: :nounzip\n      sha256 "${file.sha256}"\n    end`;
    });
    return `  on_${os} do\n${architectures.join("\n")}\n  end`;
  });
  return `# Generated by scripts/cli-homebrew.mjs from a verified release manifest.
class G1t < Formula
  desc "Work with g1t repositories, issues and pull requests"
  homepage "https://g1t.sh"
  version "${manifest.version}"
  license "MIT"

${blocks.join("\n\n")}

  def install
    os = OS.mac? ? "macos" : "linux"
    arch = Hardware::CPU.arm? ? "arm64" : "x64"
    bin.install "g1t-#{os}-#{arch}" => "g1t"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/g1t --version")
    assert_match "Usage:", shell_output("#{bin}/g1t issue --help")
  end
end
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [, , manifest, destination] = process.argv;
  assert.ok(manifest && destination, "usage: node scripts/cli-homebrew.mjs VERIFIED_MANIFEST FORMULA.rb");
  writeFileSync(destination, homebrewFormula(JSON.parse(readFileSync(manifest, "utf8"))));
}
